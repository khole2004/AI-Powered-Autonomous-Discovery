def _print_result(result):
    """Pretty-print one analysis result, with a loud banner if it is a mock."""
    if result["is_mock"]:
        print("!" * 72)
        print("!!  MOCK RESULT - NOT AI-GENERATED. No model analysed this image. !!")
        print("!" * 72)
    else:
        print(f"AI-generated result from model '{result['model']}' "
              "(review before relying on it).")
    print(f"Status   : {result['status']}  "
          f"({result['duration_seconds']} s, source {result['source']})")
    for field in ANALYSIS_FIELDS:
        value = result["analysis"][field]
        if isinstance(value, (list, dict)):
            value = json.dumps(value, ensure_ascii=True)
        shown = "(not provided)" if value is None else str(value)
        label = field.replace("_", " ").capitalize()
        print(f"  {label:<28}: "
              f"{shown.encode('ascii', 'replace').decode('ascii')}")
    if result["missing_fields"]:
        print(f"  Missing fields: {', '.join(result['missing_fields'])}")


def _parse_args(argv=None):
    """Command-line options for the demo."""
    project_root = Path(__file__).resolve().parents[2]
    default_image = (project_root / "sample_pdfs" / "extracted_figures"
                     / "page04_img01.png")

    parser = argparse.ArgumentParser(
        description="Analyse a figure image with a vision-language model.")
    parser.add_argument("image", nargs="?", default=str(default_image),
                        help="PNG/JPEG figure image (default: a sample figure)")
    parser.add_argument("--caption", default=None,
                        help="figure caption, used as context")
    parser.add_argument("--model", default=None,
                        help=f"Ollama model name (default: VLM_MODEL or '{DEFAULT_MODEL}')")
    parser.add_argument("--url", default=None,
                        help="Ollama server URL (default: OLLAMA_HOST or "
                             f"{DEFAULT_OLLAMA_URL})")
    parser.add_argument("--timeout", type=float, default=DEFAULT_TIMEOUT_SECONDS,
                        help="seconds to wait for the model")
    parser.add_argument("--mock", action="store_true", default=None,
                        help="use MockVLMClient: no server, no model, "
                             "placeholder results (or set VLM_MOCK=1)")
    parser.add_argument("--scenario", choices=MOCK_SCENARIOS, default="ok",
                        help="mock scenario to simulate (only with --mock)")
    return parser.parse_args(argv)


if __name__ == "__main__":

    args = _parse_args()
    client = create_client(mock=args.mock, scenario=args.scenario,
                           model=args.model, base_url=args.url,
                           timeout=args.timeout)

    mode = (f"MOCK (scenario '{client.scenario}') - no AI model is used"
            if client.is_mock else "real (Ollama)")
    print(f"Mode          : {mode}")
    print(f"Ollama server : {client.base_url}")
    print(f"Model         : {client.model}")
    print(f"Image         : {args.image}")
    print(f"Caption       : {args.caption or '(none)'}")
    print()

    # 1. Validate the image first - this works with no model installed.
    try:
        validate_image(args.image)
        print("Image check   : OK (valid PNG/JPEG)")
    except (FileNotFoundError, ValueError) as error:
        print(f"Image check   : FAILED - {error}")
        raise SystemExit(1)

    # 2. Is the model actually available?
    readiness = client.check_ready()
    print(f"Server        : "
          f"{'reachable' if readiness['server_reachable'] else 'NOT reachable'}"
          f"{' (simulated)' if client.is_mock else ''}")
    if readiness["server_reachable"]:
        print(f"Installed     : {readiness['installed_models'] or '(no models)'}")
    print(f"Status        : {readiness['message']}")

    if not readiness["model_available"]:
        print()
        print("Analysis skipped - the VLM is not available.")
        if not client.is_mock:
            print("To test the workflow without a model, add --mock")
        raise SystemExit(2)

    # 3. Analysis (real or mock).
    print()
    try:
        _print_result(client.analyze_figure(args.image, args.caption))
    except VLMError as error:
        print(f"Analysis FAILED - {type(error).__name__}: {error}")
        raise SystemExit(3)

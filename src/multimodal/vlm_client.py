def _default_base_url():
    """
    Server address: the OLLAMA_HOST environment variable if set (Ollama's own
    convention, e.g. "127.0.0.1:11434"), otherwise the standard local address.
    """
    host = os.environ.get("OLLAMA_HOST", "").strip()
    if not host:
        return DEFAULT_OLLAMA_URL
    if not host.startswith(("http://", "https://")):
        host = "http://" + host
    return host


def _default_model():
    """Model name: the VLM_MODEL environment variable if set, else 'llava'."""
    return os.environ.get("VLM_MODEL", "").strip() or DEFAULT_MODEL


def _env_flag(name):
    """True if environment variable `name` is set to 1/true/yes/on."""
    return os.environ.get(name, "").strip().lower() in ("1", "true", "yes", "on")


class VLMClient:
    """
    A small, reusable client for a vision-language model served by Ollama.

    Example
    -------
        client = VLMClient()                 # llava on localhost:11434
        print(client.check_ready())          # is everything installed?
        result = client.analyze_figure("fig.png", caption="Figure 2: ...")
        print(result["analysis"]["chart_type"])

    Any vision model Ollama serves can be used by name, e.g.
    `VLMClient(model="llava:13b")` - nothing else in the code changes.
    """

    # Subclasses that do not use a real model set this to True; it is copied
    # into every result so mock output can never pass as AI output.
    is_mock = False

    def __init__(self, model=None, base_url=None,
                 timeout=DEFAULT_TIMEOUT_SECONDS):
        self.model = model or _default_model()
        self.base_url = (base_url or _default_base_url()).rstrip("/")
        self.timeout = timeout

    # ----- low-level HTTP -------------------------------------------------

    def _request(self, method, endpoint, payload=None, timeout=None):
        """
        Send one HTTP request to Ollama and return the decoded JSON reply.

        Every network failure is translated into one of our own error types,
        each with a message that tells a beginner what to do next.
        """
        url = f"{self.base_url}{endpoint}"
        data = json.dumps(payload).encode("utf-8") if payload is not None else None
        request = urllib.request.Request(
            url, data=data, method=method,
            headers={"Content-Type": "application/json"})

        try:
            with urllib.request.urlopen(request, timeout=timeout or self.timeout) as reply:
                body = reply.read().decode("utf-8")

        except urllib.error.HTTPError as error:
            # The server answered, but with an error status (e.g. 404).
            detail = ""
            try:
                detail = json.loads(error.read().decode("utf-8")).get("error", "")
            except Exception:
                pass
            if error.code == 404 and "not found" in detail.lower():
                raise VLMModelError(
                    f"Model '{self.model}' is not installed on the Ollama server "
                    f"({detail}). Download it with:  ollama pull {self.model}"
                ) from error
            raise VLMModelError(
                f"Ollama returned HTTP {error.code} for {endpoint}: "
                f"{detail or error.reason}") from error

        except (socket.timeout, TimeoutError) as error:
            raise VLMConnectionError(
                f"Ollama at {self.base_url} did not answer within "
                f"{timeout or self.timeout} s. The first request can be slow "
                f"while the model loads; try a larger timeout.") from error

        except urllib.error.URLError as error:
            # Nothing listening, DNS failure, refused connection, ...
            if isinstance(error.reason, (socket.timeout, TimeoutError)):
                raise VLMConnectionError(
                    f"Ollama at {self.base_url} timed out.") from error
            raise VLMConnectionError(
                f"Cannot reach Ollama at {self.base_url} ({error.reason}). "
                f"Is Ollama installed and running? Start it with:  ollama serve"
            ) from error

        try:
            decoded = json.loads(body)
        except json.JSONDecodeError as error:
            raise VLMResponseError(
                f"Ollama sent a reply that is not JSON: {body[:200]!r}") from error

        if isinstance(decoded, dict) and decoded.get("error"):
            raise VLMModelError(f"Ollama reported an error: {decoded['error']}")

        return decoded

    # ----- readiness checks ----------------------------------------------

    def list_models(self):
        """Names of the models installed on the server, e.g. ['llava:latest']."""
        reply = self._request("GET", "/api/tags", timeout=10)
        return [m.get("name", "") for m in reply.get("models", [])]

    def is_model_available(self, installed=None):
        """
        True if `self.model` is installed.

        Ollama treats a name without a tag as ':latest', so "llava" matches
        "llava:latest" but NOT "llava:13b".
        """
        if installed is None:
            installed = self.list_models()
        wanted = self.model if ":" in self.model else f"{self.model}:latest"
        return wanted in installed or self.model in installed

    def check_ready(self):
        """
        Report whether real analysis can run, without raising.

        Returns:
            {"mode": "ollama", "server_reachable": bool,
             "model_available": bool, "installed_models": [...],
             "message": "what to do next"}
        """
        status = {"mode": "ollama", "server_reachable": False,
                  "model_available": False, "installed_models": [],
                  "message": ""}
        try:
            installed = self.list_models()
        except VLMError as error:
            status["message"] = str(error)
            return status

        status["server_reachable"] = True
        status["installed_models"] = installed
        status["model_available"] = self.is_model_available(installed)
        if status["model_available"]:
            status["message"] = f"Ready: '{self.model}' is available."
        else:
            status["message"] = (
                f"Ollama is running but '{self.model}' is not installed. "
                f"Download it with:  ollama pull {self.model}")
        return status

    # ----- the main job --------------------------------------------------

    def analyze_figure(self, image_path, caption=None):
        """
        Ask the VLM for a structured description of one figure image.

        Parameters
        ----------
        image_path : str | Path   PNG or JPEG figure image.
        caption : str, optional   The figure's caption, used as context.

        Returns
        -------
        dict:
            {
                "image_path": "...",
                "caption": "Figure 2: ..." | None,
                "model": "llava",
                "is_mock": False,             # True only for MockVLMClient
                "source": "ollama" | "mock",
                "disclaimer": None | "MOCK RESULT - ...",
                "status": "ok" | "partial" | "unstructured",
                "analysis": {the eight ANALYSIS_FIELDS, None if not given},
                "missing_fields": [...],
                "raw_response": "<exact text the model returned>",
                "duration_seconds": 12.3,
            }

        Raises
        ------
        FileNotFoundError, ValueError  - bad image (checked BEFORE any network
                                         call, so no time is wasted).
        VLMConnectionError             - Ollama unreachable / timed out.
        VLMModelError                  - model missing or model-side error.
        VLMResponseError               - reply could not be understood.
        """
        # Steps 1-2 and 4-5 are shared by real and mock mode; only step 3
        # (`_generate`) differs, so mock mode really exercises the workflow.

        # 1. Validate the image (no network call yet).
        path = validate_image(image_path)

        # 2. Build the request contents.
        prompt = build_prompt(caption)
        image_b64 = encode_image(path)

        # 3. Get the model's raw text reply.
        started = time.perf_counter()
        response_text = self._generate(prompt, image_b64, path)
        duration = time.perf_counter() - started

        if not isinstance(response_text, str) or not response_text.strip():
            raise VLMResponseError(
                "The model returned an empty response for "
                f"{path.name}. Try again, or check the model with "
                f"'ollama run {self.model}'.")

        # 4. Parse it into the eight fields.
        analysis, missing, status = parse_analysis(response_text)

        # 5. Assemble the result, labelled with where it came from.
        return {
            "image_path": str(path),
            "caption": caption,
            "model": self.model,
            "is_mock": self.is_mock,
            "source": "mock" if self.is_mock else "ollama",
            "disclaimer": MOCK_DISCLAIMER if self.is_mock else None,
            "status": status,
            "analysis": analysis,
            "missing_fields": missing,
            "raw_response": response_text,
            "duration_seconds": round(duration, 2),
        }

    def _generate(self, prompt, image_b64, path):
        """
        Send one prompt + image to Ollama and return the model's text reply.

        This is the ONLY step that differs in MockVLMClient.
        """
        payload = {
            "model": self.model,
            "prompt": prompt,
            "images": [image_b64],
            "stream": False,                 # one complete reply, not chunks
            "format": "json",                # ask Ollama to force JSON output
            "options": {"temperature": 0},   # same figure -> same answer
        }
        reply = self._request("POST", "/api/generate", payload)
        return reply.get("response")



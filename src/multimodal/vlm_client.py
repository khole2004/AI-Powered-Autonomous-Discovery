class MockVLMClient(VLMClient):
    """
    A stand-in for VLMClient that NEVER contacts a server or loads a model.

    Use it to test the figure-analysis workflow (and the code that consumes
    its results) on a machine without Ollama. Image validation, prompt
    building, parsing and result assembly are the real, shared code; only the
    model call is replaced by a canned reply.

    Every result is labelled as mock (`is_mock=True`, `source="mock"`, a
    `disclaimer`, and "[MOCK]" in front of every analysis value). A mock result
    must never be presented or stored as real AI analysis.

    Scenarios (choose with `scenario=`), so error handling can be tested too:
        "ok"               all eight fields                 -> status "ok"
        "partial"          only summary and chart type      -> status "partial"
        "unstructured"     plain text, not JSON             -> status "unstructured"
        "empty"            blank reply                      -> VLMResponseError
        "model_missing"    as if the model is not installed -> VLMModelError
        "connection_error" as if Ollama is not running      -> VLMConnectionError

    `calls` records every (image_path, prompt) the mock received, so a test
    can check exactly what would have been sent to the model.
    """

    is_mock = True

    def __init__(self, scenario="ok", model=None, base_url=None,
                 timeout=DEFAULT_TIMEOUT_SECONDS):
        if scenario not in MOCK_SCENARIOS:
            raise ValueError(
                f"Unknown mock scenario '{scenario}'. "
                f"Choose one of: {', '.join(MOCK_SCENARIOS)}")
        super().__init__(model=model, base_url=base_url, timeout=timeout)
        self.scenario = scenario
        self.calls = []

    def _mock_analysis(self, path):
        """The canned eight-field reply; every value carries MOCK_PREFIX."""
        return {
            "figure_summary": f"{MOCK_PREFIX} Placeholder for {path.name}. "
                              "No AI model analysed this image.",
            "chart_type": f"{MOCK_PREFIX} not analysed",
            "x_axis": f"{MOCK_PREFIX} not analysed",
            "y_axis": f"{MOCK_PREFIX} not analysed",
            "trends_and_patterns": f"{MOCK_PREFIX} not analysed",
            "legend": f"{MOCK_PREFIX} not analysed",
            "important_observations": [f"{MOCK_PREFIX} placeholder observation"],
            "limitations_or_uncertainty": f"{MOCK_PREFIX} {MOCK_DISCLAIMER}",
        }

    def _generate(self, prompt, image_b64, path):
        """Return a canned reply (or raise a canned error) - no network."""
        self.calls.append({"image_path": str(path), "prompt": prompt})

        if self.scenario == "connection_error":
            raise VLMConnectionError(
                f"{MOCK_PREFIX} Simulated: cannot reach Ollama at "
                f"{self.base_url}. Is Ollama installed and running?")
        if self.scenario == "model_missing":
            raise VLMModelError(
                f"{MOCK_PREFIX} Simulated: model '{self.model}' is not "
                f"installed. Download it with:  ollama pull {self.model}")
        if self.scenario == "empty":
            return ""
        if self.scenario == "unstructured":
            return (f"{MOCK_PREFIX} This simulated reply is plain text rather "
                    "than JSON, as a real model sometimes returns.")

        analysis = self._mock_analysis(path)
        if self.scenario == "partial":
            analysis = {key: analysis[key]
                        for key in ("figure_summary", "chart_type")}
        return json.dumps(analysis)

    def list_models(self):
        """Simulated model list; never contacts a server."""
        if self.scenario == "connection_error":
            raise VLMConnectionError(
                f"{MOCK_PREFIX} Simulated: cannot reach Ollama at {self.base_url}.")
        if self.scenario == "model_missing":
            return []
        return [self.model if ":" in self.model else f"{self.model}:latest"]

    def check_ready(self):
        """Readiness in mock mode - always says plainly that it is a mock."""
        status = {"mode": "mock", "server_reachable": False,
                  "model_available": False, "installed_models": [],
                  "message": ""}
        try:
            installed = self.list_models()
        except VLMError as error:
            status["message"] = str(error)
            return status
        status["server_reachable"] = True      # simulated
        status["installed_models"] = installed
        status["model_available"] = self.is_model_available(installed)
        if status["model_available"]:
            status["message"] = (
                f"{MOCK_PREFIX} Mock mode (scenario '{self.scenario}'): no "
                "server is contacted and no AI model runs. Results are "
                "placeholders.")
        else:
            status["message"] = (
                f"{MOCK_PREFIX} Simulated: model '{self.model}' is not installed.")
        return status


def create_client(mock=None, scenario="ok", model=None, base_url=None,
                  timeout=DEFAULT_TIMEOUT_SECONDS):
    """
    Build the right client for the current setup.

    `mock=None` (the default) reads the VLM_MOCK environment variable, so a
    pipeline can be switched into mock mode without changing any code:

        set VLM_MOCK=1          (Windows)    export VLM_MOCK=1   (Linux/macOS)
    """
    if mock is None:
        mock = _env_flag("VLM_MOCK")
    if mock:
        return MockVLMClient(scenario=scenario, model=model,
                             base_url=base_url, timeout=timeout)
    return VLMClient(model=model, base_url=base_url, timeout=timeout)


# ---------------------------------------------------------------------------
# Batch helper for figure_extractor-style records
# ---------------------------------------------------------------------------

def analyze_figures(figure_records, client=None):
    """
    Analyse many figures, never stopping because one of them fails.

    `figure_records` is any list of dictionaries with a "file_path" key and,
    optionally, "caption" - for example `extract_all(...)["figure_regions"]`.
    Records without a file_path (e.g. a figure that could not be located)
    are reported as skipped.

    Returns one dict per input record, in the same order:

        {"record": <the original input record>,
         "is_mock": True | False,       # which kind of client produced it
         "status": "ok" | "partial" | "unstructured" | "skipped" | "error",
         "result": <analyze_figure result> | None,
         "error": "message" | None}

    If the server itself is unreachable, every remaining figure would fail the
    same way, so the batch stops trying and marks the rest as errors with the
    same message instead of waiting for a timeout on each one.

    `client` defaults to `create_client()`, so setting VLM_MOCK=1 switches a
    whole batch into mock mode.
    """
    client = client or create_client()
    results = []
    connection_problem = None

    for record in figure_records:
        entry = {"record": record, "is_mock": client.is_mock,
                 "status": "error", "result": None, "error": None}

        image_path = record.get("file_path")
        if not image_path:
            entry["status"] = "skipped"
            entry["error"] = "Record has no file_path (no image was saved)."
        elif connection_problem:
            entry["error"] = connection_problem
        else:
            try:
                result = client.analyze_figure(image_path, record.get("caption"))
                entry["status"] = result["status"]
                entry["result"] = result
            except VLMConnectionError as error:
                connection_problem = str(error)
                entry["error"] = connection_problem
            except (FileNotFoundError, ValueError, VLMError) as error:
                entry["error"] = str(error)

        results.append(entry)

    return results



"""
Module 4 - Multimodal Ingestion: Vision-Language Model (VLM) client.

Sends an extracted figure image (plus its caption, if known) to LLaVA running
under Ollama and asks for a STRUCTURED scientific description of the chart:

    figure_summary, chart_type, x_axis, y_axis, trends_and_patterns,
    legend, important_observations, limitations_or_uncertainty

How it talks to the model
-------------------------
Ollama runs a local HTTP server (default http://localhost:11434). We call its
`POST /api/generate` endpoint with the image encoded as base64 text. Only the
Python standard library is used (`urllib`, `json`, `base64`), so this module
adds no new package dependencies.

Where its input comes from
--------------------------
`figure_extractor.py` writes figure images and returns records containing
`file_path` and (for figure-region crops) `caption`. This module does NOT
import figure_extractor - it just accepts a path and an optional caption, or a
list of plain dictionaries with those keys - so the modules stay decoupled.

Two modes
---------
  * Real mode   (`VLMClient`)      - talks to an Ollama server. Needs setup:
        1. Install Ollama            https://ollama.com/download
        2. Download a vision model   ollama pull llava      (several GB)
        3. Make sure it is running   ollama serve           (often automatic)
  * Mock mode   (`MockVLMClient`)  - NEVER contacts a server and needs no
        model. It runs the same validation, prompt-building and parsing code,
        but returns a canned placeholder reply, so the whole workflow can be
        tested on any machine. Mock results are clearly labelled in four ways:
        `is_mock: True`, `source: "mock"`, a `disclaimer`, and a "[MOCK]"
        prefix on every analysis value. They are NOT AI analysis.

Configuration (constructor argument > environment variable > default):
    model name   model=...     VLM_MODEL     "llava"
    server URL   base_url=...  OLLAMA_HOST   "http://localhost:11434"
    mock mode    mock=...      VLM_MOCK=1    off   (see `create_client`)

Run directly to try it:

    python src/multimodal/vlm_client.py IMAGE [--caption TEXT] [--mock]
                                              [--model NAME] [--url URL]
"""

import argparse
import base64
import json
import os
import re
import socket
import time
import urllib.error
import urllib.request
from pathlib import Path


# ---------------------------------------------------------------------------
# Configuration constants
# ---------------------------------------------------------------------------

DEFAULT_OLLAMA_URL = "http://localhost:11434"
DEFAULT_MODEL = "llava"

# Generating a description can be slow, especially the first call while the
# model loads into memory, so the default timeout is generous.
DEFAULT_TIMEOUT_SECONDS = 300

# Formats LLaVA/Ollama reliably accept. We check the file's real signature
# ("magic bytes") as well as its extension, so a renamed file is caught.
SUPPORTED_EXTENSIONS = {".png", ".jpg", ".jpeg"}
IMAGE_SIGNATURES = {
    "png": b"\x89PNG\r\n\x1a\n",
    "jpeg": b"\xff\xd8\xff",
}

# Refuse absurdly large files: base64 adds ~33%, and a vision model only
# needs a reasonably sized picture.
MAX_IMAGE_BYTES = 20 * 1024 * 1024

# The eight fields every analysis result contains, in a fixed order.
ANALYSIS_FIELDS = [
    "figure_summary",
    "chart_type",
    "x_axis",
    "y_axis",
    "trends_and_patterns",
    "legend",
    "important_observations",
    "limitations_or_uncertainty",
]

# Models do not always use our exact key names. These alternative spellings
# are mapped back to the official field names when the reply is parsed.
FIELD_ALIASES = {
    "summary": "figure_summary",
    "figure_description": "figure_summary",
    "description": "figure_summary",
    "type": "chart_type",
    "figure_type": "chart_type",
    "graph_type": "chart_type",
    "x_axis_information": "x_axis",
    "xaxis": "x_axis",
    "y_axis_information": "y_axis",
    "yaxis": "y_axis",
    "trends": "trends_and_patterns",
    "patterns": "trends_and_patterns",
    "legend_information": "legend",
    "legends": "legend",
    "observations": "important_observations",
    "key_observations": "important_observations",
    "limitations": "limitations_or_uncertainty",
    "uncertainty": "limitations_or_uncertainty",
    "limitations_and_uncertainty": "limitations_or_uncertainty",
}

# ----- mock mode -----------------------------------------------------------

# Every value a mock produces starts with this marker, so a mock value can be
# recognised even after it is copied out of its result dictionary.
MOCK_PREFIX = "[MOCK]"

MOCK_DISCLAIMER = (
    "MOCK RESULT - generated by MockVLMClient without any AI model. It is a "
    "placeholder for testing the workflow and says nothing about the figure.")

# What MockVLMClient can pretend to do. Each name maps to the behaviour
# described in MockVLMClient's docstring.
MOCK_SCENARIOS = ("ok", "partial", "unstructured", "empty",
                  "model_missing", "connection_error")


# ---------------------------------------------------------------------------
# Errors
# ---------------------------------------------------------------------------
# Image problems use Python's built-in FileNotFoundError / ValueError, the same
# as pdf_parser and figure_extractor. Problems talking to the model get their
# own classes so a caller can react to each one differently.

class VLMError(Exception):
    """Base class for every error raised while talking to the VLM."""


class VLMConnectionError(VLMError):
    """The Ollama server could not be reached, or did not answer in time."""


class VLMModelError(VLMError):
    """The server answered with an error (e.g. the model is not installed)."""


class VLMResponseError(VLMError):
    """The server replied, but the reply could not be understood."""


# ---------------------------------------------------------------------------
# Image validation and encoding
# ---------------------------------------------------------------------------

def validate_image(image_path):
    """
    Check that `image_path` is a usable PNG or JPEG image.

    Returns the path as a `Path` object. Raises:
        FileNotFoundError - the path does not exist or is a folder.
        ValueError        - wrong extension, empty, too large, or the file's
                            contents are not really a PNG/JPEG.
    """
    path = Path(image_path)

    if not path.exists():
        raise FileNotFoundError(f"Image not found: {path}")
    if not path.is_file():
        raise FileNotFoundError(f"Not a file: {path}")

    if path.suffix.lower() not in SUPPORTED_EXTENSIONS:
        supported = ", ".join(sorted(SUPPORTED_EXTENSIONS))
        raise ValueError(
            f"Unsupported image format '{path.suffix}' for {path.name}. "
            f"Supported: {supported}")

    size = path.stat().st_size
    if size == 0:
        raise ValueError(f"Image file is empty: {path}")
    if size > MAX_IMAGE_BYTES:
        raise ValueError(
            f"Image is too large ({size:,} bytes, limit {MAX_IMAGE_BYTES:,}): {path}")

    # The extension can lie (e.g. a .txt renamed to .png); the first bytes
    # of the file cannot.
    with open(path, "rb") as handle:
        header = handle.read(8)
    if not any(header.startswith(sig) for sig in IMAGE_SIGNATURES.values()):
        raise ValueError(f"File is not a valid PNG or JPEG image: {path}")

    return path


def encode_image(image_path):
    """Read an image and return it as a base64 text string for the API."""
    with open(image_path, "rb") as handle:
        return base64.b64encode(handle.read()).decode("ascii")


# ---------------------------------------------------------------------------
# Prompt construction
# ---------------------------------------------------------------------------

def build_prompt(caption=None):
    """
    Build the chart-analysis instruction sent alongside the image.

    The caption (if any) is given as CONTEXT only. The model is told to
    describe what is actually visible and to say "not visible" instead of
    inventing values - a vision model that guesses is worse than useless for
    a statistical critic.
    """
    lines = [
        "You are analysing a figure taken from a scientific research paper.",
        "Describe ONLY what is visible in the image. If something cannot be "
        "read clearly (for example small axis labels), say so instead of "
        "guessing. Do not invent numbers.",
    ]

    if caption:
        lines.append(
            "The paper's caption for this figure is given below as context. "
            "Use it to understand the figure, but report what the image shows; "
            "if the image and caption disagree, mention it.")
        lines.append(f'Caption: "{caption.strip()}"')
    else:
        lines.append("No caption is available for this figure.")

    lines.append(
        "Reply with a single JSON object with exactly these keys:\n"
        '  "figure_summary": one or two sentences on what the figure shows,\n'
        '  "chart_type": e.g. bar chart, line plot, scatter plot, diagram, '
        "table, photograph, or other,\n"
        '  "x_axis": the x-axis label, units and range, or "not applicable",\n'
        '  "y_axis": the y-axis label, units and range, or "not applicable",\n'
        '  "trends_and_patterns": the main trends, comparisons or patterns,\n'
        '  "legend": the legend entries and what they mean, or "none",\n'
        '  "important_observations": a list of short notable findings,\n'
        '  "limitations_or_uncertainty": anything unreadable, ambiguous or '
        "uncertain in your reading of the figure.")

    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Response parsing
# ---------------------------------------------------------------------------

def _normalise_key(key):
    """'X-Axis Information' -> 'x_axis_information'."""
    return re.sub(r"[^a-z0-9]+", "_", str(key).lower()).strip("_")


def _extract_json_object(text):
    """
    Pull a JSON object out of the model's text reply.

    With Ollama's `format: "json"` the reply should already be pure JSON,
    but models sometimes wrap it in ```json fences or add a sentence first,
    so we fall back to the first {...} block. Returns a dict or None.
    """
    candidates = [text.strip()]

    fenced = re.search(r"```(?:json)?\s*(\{.*\})\s*```", text, re.DOTALL)
    if fenced:
        candidates.append(fenced.group(1))

    first, last = text.find("{"), text.rfind("}")
    if first != -1 and last > first:
        candidates.append(text[first:last + 1])

    for candidate in candidates:
        try:
            parsed = json.loads(candidate)
        except (json.JSONDecodeError, ValueError):
            continue
        if isinstance(parsed, dict):
            return parsed
    return None


def _is_empty(value):
    """True for None, blank strings and empty lists/dicts."""
    if value is None:
        return True
    if isinstance(value, str):
        return not value.strip()
    if isinstance(value, (list, dict)):
        return len(value) == 0
    return False


def parse_analysis(response_text):
    """
    Turn the model's raw reply into the eight-field analysis.

    Returns a tuple (analysis, missing_fields, status):

        analysis       - dict with ALL eight ANALYSIS_FIELDS; a field the
                         model did not provide is None (never invented).
        missing_fields - list of field names that came back empty/absent.
        status         - "ok"           every field present
                         "partial"      valid JSON, some fields missing
                         "unstructured" reply was not JSON at all (the raw
                                        text is still kept by the caller)
    """
    analysis = {field: None for field in ANALYSIS_FIELDS}

    parsed = _extract_json_object(response_text or "")
    if parsed is None:
        return analysis, list(ANALYSIS_FIELDS), "unstructured"

    for key, value in parsed.items():
        name = _normalise_key(key)
        name = FIELD_ALIASES.get(name, name)
        if name in analysis and not _is_empty(value):
            # Keep strings tidy; lists/dicts are kept as the model gave them.
            analysis[name] = value.strip() if isinstance(value, str) else value

    missing = [field for field in ANALYSIS_FIELDS if analysis[field] is None]
    status = "ok" if not missing else "partial"
    return analysis, missing, status


